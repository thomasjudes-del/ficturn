export const storyIds = stories.map((item) => item.id);

export function getStory(storyId = DEFAULT_STORY_ID) {
  const found = stories.find((item) => item.id === storyId);
  if (!found) throw new Error(`Unknown story ${storyId}`);
  return found;
}

export function getFragment(storyId: string, part: number) {
  const story = getStory(storyId);
  const index = part - 1;
  if (!Number.isInteger(part) || index < 0 || index >= story.fragments.length) {
    throw new Error(`Invalid fragment ${part} for ${storyId}`);
  }
  return story.fragments[index];
}

export function getStorySummaries() {
  return stories.map(({ fragments, ...summary }) => summary);
}
